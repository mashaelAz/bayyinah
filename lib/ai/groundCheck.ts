import { normalizeArabic } from '../arabic/normalize.ts';

/**
 * فحص إسناد إجابة «اسأل بيّنة» بعد توليدها (مقاومة الهلوسة).
 *
 * المبدأ: كل معلومة «قابلة للتحقق» تذكرها الإجابة يجب أن توجد في بيانات النتيجة المسترجعة:
 * - الأرقام (أرقام الأحاديث والآيات والنسب)
 * - أسماء كتب الحديث
 * - أسماء المحدّثين والعلماء
 * - أسماء السور
 * - ألفاظ الأحكام إذا نُسبت إلى الحديث («الحديث صحيح»، «حكمه ضعيف»…)
 * إذا ذكرت الإجابة شيئًا من ذلك ليس في البيانات، تُعدّ غير مسندة فتُحجب.
 * الفحص بالقواعد، لا بنموذج لغوي، فنتيجته ثابتة وقابلة للاختبار.
 */

export interface GroundCheck {
  ok: boolean;
  /** ما ذكرته الإجابة وليس في البيانات */
  issues: string[];
}

const BOOKS = [
  'صحيح البخاري', 'صحيح مسلم', 'سنن ابي داود', 'جامع الترمذي', 'سنن الترمذي', 'سنن النسائي', 'سنن ابن ماجه',
  'مسند احمد', 'موطا مالك', 'الموطا', 'صحيح ابن حبان', 'صحيح ابن خزيمه', 'المستدرك', 'سنن الدارمي', 'سنن البيهقي',
  'السنن الكبري', 'المعجم الكبير', 'المعجم الاوسط', 'شعب الايمان', 'مجمع الزوائد', 'السلسله الصحيحه',
  'السلسله الضعيفه', 'صحيح الجامع', 'ضعيف الجامع', 'صحيح الترغيب', 'ضعيف الترغيب', 'الادب المفرد',
  'رياض الصالحين', 'الاربعين النوويه', 'بلوغ المرام', 'فتح الباري', 'مشكاه المصابيح',
];

/** أسماء لا تلتبس بكلمات عامة («مسلم» و«أحمد» وحدهما تلتبسان، فتُفحص بصيغ النسبة) */
const SCHOLARS = [
  'البخاري', 'الالباني', 'ابن حجر', 'الذهبي', 'النووي', 'ابن باز', 'ابن عثيمين', 'ابن تيميه', 'ابن القيم',
  'الترمذي', 'النسائي', 'ابن ماجه', 'ابو داود', 'البيهقي', 'الطبراني', 'الدارقطني', 'ابن حبان',
  'ابن خزيمه', 'احمد شاكر', 'شعيب الارناووط', 'الارناووط', 'بشار عواد', 'زبير علي زي', 'السيوطي',
  'ابن الجوزي', 'ابن عدي', 'الهيثمي', 'المنذري', 'ابن الملقن', 'ابو نعيم', 'الامام مسلم', 'رواه مسلم',
  'اخرجه مسلم', 'الامام احمد', 'رواه احمد', 'اخرجه احمد',
];

const GRADES = [
  'صحيح', 'حسن', 'ضعيف', 'ضعيف جدا', 'موضوع', 'مكذوب', 'باطل', 'منكر', 'شاذ', 'متواتر', 'لا اصل له', 'مرسل', 'موقوف',
];

const SURAHS =
  'الفاتحه البقره ال عمران النساء المايده الانعام الاعراف الانفال التوبه يونس هود يوسف الرعد ابراهيم الحجر النحل الاسراء الكهف مريم طه الانبياء الحج المومنون النور الفرقان الشعراء النمل القصص العنكبوت الروم لقمان السجده الاحزاب سبا فاطر يس الصافات ص الزمر غافر فصلت الشوري الزخرف الدخان الجاثيه الاحقاف محمد الفتح الحجرات ق الذاريات الطور النجم القمر الرحمن الواقعه الحديد المجادله الحشر الممتحنه الصف الجمعه المنافقون التغابن الطلاق التحريم الملك القلم الحاقه المعارج نوح الجن المزمل المدثر القيامه الانسان المرسلات النبا النازعات عبس التكوير الانفطار المطففين الانشقاق البروج الطارق الاعلي الغاشيه الفجر البلد الشمس الليل الضحي الشرح التين العلق القدر البينه الزلزله العاديات القارعه التكاثر العصر الهمزه الفيل قريش الماعون الكوثر الكافرون النصر المسد الاخلاص الفلق الناس';

function toLatinDigits(s: string): string {
  return s.replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d))).replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)));
}

/** نص مطبّع محاط بمسافات، للبحث عن كلمة أو عبارة كاملة، مع توحيد الصيغ المتكافئة */
function norm(s: string): string {
  return ` ${normalizeArabic(toLatinDigits(s))} `
    .replace(/ ابي /g, ' ابو ')
    .replace(/ سنن الترمذي /g, ' جامع الترمذي ')
    .replace(/ صحيح ابن ماجه /g, ' سنن ابن ماجه ');
}

const has = (hay: string, phrase: string) => hay.includes(` ${phrase} `);

export function checkGrounding(answer: string, context: string, question = ''): GroundCheck {
  const a = norm(answer);
  const c = norm(context);
  const q = norm(question);
  const issues = new Set<string>();

  // 1) الأرقام: كل رقم في الإجابة يجب أن يكون في البيانات أو في سؤال المستخدم
  const ctxNums = new Set((toLatinDigits(context + ' ' + question).match(/\d+/g) ?? []).map((n) => String(Number(n))));
  // أرقام القوائم في أول السطر («1.» «2)») ليست معلومات
  const body = toLatinDigits(answer).replace(/^\s*\d{1,2}\s*[.)\-]\s/gm, ' ');
  for (const n of body.match(/\d+/g) ?? []) {
    const v = String(Number(n));
    if (!ctxNums.has(v)) issues.add(n);
  }

  // 2) كتب الحديث
  for (const b of BOOKS) if (has(a, b) && !has(c, b) && !has(q, b)) issues.add(b);

  // 3) المحدّثون والعلماء
  for (const s of SCHOLARS) {
    if (!has(a, s) || has(q, s)) continue;
    // «رواه مسلم» تكفي أن يكون «مسلم» محدّثًا في البيانات
    const core = s.replace(/^(الامام|رواه|اخرجه) /, '');
    if (!has(c, s) && !has(c, core)) issues.add(s);
  }

  // 4) أسماء السور (بعد كلمة «سوره»)
  for (const m of a.matchAll(/ سوره (ال )?(\S+)/g)) {
    const name = (m[1] ? 'ال ' : '') + m[2];
    if (!SURAHS.includes(m[2]) && !SURAHS.includes(name)) continue;
    if (!c.includes(` ${m[2]} `)) issues.add(`سورة ${m[2]}`);
  }

  // 5) ألفاظ الأحكام إذا نُسبت إلى الحديث: تُقارن بأسطر الحكم في البيانات فقط
  // (حتى لا تُحسب «صحيح» في اسم «صحيح البخاري» حكمًا)
  const gradeLines = norm(
    context
      .split('\n')
      .filter((l) => /حكم|^- /.test(l.trim()))
      .map((l) => l.replace(/صحيح البخاري|صحيح مسلم/g, ' '))
      .join(' '),
  );
  for (const g of GRADES) {
    const claim = new RegExp(` (الحديث|هذا الحديث|حكمه|حكمه هو|درجته|فهو|وهو|حديث) (حديث )?${g} `);
    if (claim.test(a) && !has(gradeLines, g)) issues.add(g);
  }

  return { ok: issues.size === 0, issues: [...issues] };
}
